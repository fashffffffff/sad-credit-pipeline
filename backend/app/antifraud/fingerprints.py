"""Отпечатки связующих атрибутов. В графе антифрода НЕТ ни одного открытого значения: только HMAC-отпечатки.

HMAC с секретом (тем же PII_PEPPER, что и для хэша паспорта) нельзя перебрать по базе телефонов или ИНН
без знания секрета, но одинаковые значения всегда дают одинаковый отпечаток — по нему и находим связи.
"""

import hashlib
import hmac


def fingerprint(pepper: str, kind: str, value: str) -> str:
    """kind входит в хэш: один и тот же текст как телефон и как ИНН даёт разные отпечатки."""
    return hmac.new(pepper.encode(), f"{kind}:{value}".encode(), hashlib.sha256).hexdigest()[:24]

