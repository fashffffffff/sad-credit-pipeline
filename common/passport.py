# Таблица сверена с Википедией «Коды субъектов Российской Федерации» (столбцы ОКАТО и код ГИБДД): 87 из 91 совпали.
# Исключение — Крым (ГИБДД 82, а коды подразделений МВД начинаются на 91) и Севастополь (92): тут верен код подразделения.
# Сомнительные соответствия (коды менялись или не подтверждены) только предупреждают и не отказывают:
# Ингушетия, Крым, Севастополь, Чукотка, Адыгея, ЕАО, ДНР, ЛНР, Запорожская и Херсонская области, Байконур.
UNSURE = {"26", "35", "67", "77", "79", "99", "21", "43", "23", "74", "55"}


def add_years(d: date, years: int) -> date:
    try:
        return d.replace(year=d.year + years)
    except ValueError:  # 29 февраля в невисокосном году -> 1 марта
        return date(d.year + years, 3, 1)


def age_on(birth: date, today: date) -> int:
    return today.year - birth.year - ((today.month, today.day) < (birth.month, birth.day))


def is_magic(passport: str) -> bool:
    return passport in MAGIC_PASSPORTS


def parse_series(passport: str) -> tuple[str, int]:
    """'4510 123456' -> ('45', 2010): регион по ОКАТО и полный год изготовления бланка."""
    region, yy = passport[:2], int(passport[2:4])
    return region, (1900 + yy if yy >= 97 else 2000 + yy)


def division_region_status(okato: str, division_code: str) -> str:
    """'ok' — код подразделения соответствует региону серии; 'mismatch' — нет; 'unknown' — не уверены."""
    subject = division_code[:2]
    if okato in UNSURE:
        if subject not in OKATO_TO_SUBJECT[okato]:
            log.warning("Соответствие серии %s и кода подразделения %s не подтверждено справочником", okato, division_code)
        return "ok" if subject in OKATO_TO_SUBJECT[okato] else "unknown"
    return "ok" if subject in OKATO_TO_SUBJECT[okato] else "mismatch"


def passport_expired(birth: date, issue: date, today: date) -> bool:
    """Правило 20/45: паспорт надо заменить, когда человеку исполняется 20 и 45 лет.

    Просрочен, если на каком-то из этих дней рождения паспорт уже был выдан ДО него
    и с этого дня прошло больше 90 дней.
    """
    for milestone in (20, 45):
        turned = add_years(birth, milestone)
        if issue < turned and today - turned > timedelta(days=EXPIRY_GRACE_DAYS):
            return True
    return False


def check_passport(passport: str, issue_date: date, division_code: str, birth: date,
                   today: date | None = None) -> dict[str, str]:
    """Возвращает ошибки по полям: passport, passport_issue_date, passport_division_code (пусто = всё хорошо).

    Предполагается, что форматы строк уже проверены (NNNN NNNNNN, NNN-NNN).
    """
    today = today or date.today()
    errors: dict[str, str] = {}
    magic = is_magic(passport)

    if not magic:
        okato, blank_year = parse_series(passport)
        if okato not in OKATO_TO_SUBJECT:
            errors["passport"] = f"Серия паспорта: региона с кодом {okato} не существует"
        elif not 1997 <= blank_year <= today.year:
            errors["passport"] = f"Серия паспорта: год изготовления бланка {blank_year} невозможен (1997–{today.year})"
        if passport[5:] == "000000":
            errors["passport"] = "Номер паспорта не может состоять из нулей"

    if issue_date > today:
        errors["passport_issue_date"] = "Дата выдачи паспорта не может быть в будущем"
    elif issue_date < add_years(birth, 14):
        errors["passport_issue_date"] = "Паспорт не мог быть выдан раньше 14-летия"
    elif issue_date < FIRST_ISSUE_DATE:
        errors["passport_issue_date"] = "Паспорта РФ выдают с 01.10.1997, дата выдачи раньше невозможна"
    elif not magic and "passport" not in errors:
        if blank_year > issue_date.year:
            errors["passport_issue_date"] = f"Бланк (серия {passport[:4]}) изготовлен в {blank_year} — позже даты выдачи"
        elif issue_date.year - blank_year > MAX_BLANK_AGE_YEARS:
            errors["passport_issue_date"] = (
                f"Бланк изготовлен в {blank_year}, а выдан в {issue_date.year}: "
                f"бланки не хранятся дольше {MAX_BLANK_AGE_YEARS} лет")

    if not magic and "passport" not in errors:
        status = division_region_status(passport[:2], division_code)
        if status == "mismatch":
            errors["passport_division_code"] = (
                f"Код подразделения {division_code} не соответствует региону серии {passport[:2]}")
    return errors
